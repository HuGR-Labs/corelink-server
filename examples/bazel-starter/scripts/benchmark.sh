#!/usr/bin/env bash
# CoreLink Bazel starter — build benchmark (com vs sem cache).
#
# Usage:
#   export CORELINK_PAT=corelink_prod_...
#   bash scripts/benchmark.sh [--iterations N] [--output BENCHMARK.md]
#
# Outputs:
#   - Table of median + p95 latency (cold vs warm) to BENCHMARK.md
#   - Cache hit ratio per warm iteration

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
WORKSPACE_DIR="$(cd "${SCRIPT_DIR}/.." && pwd)"
ITERATIONS="${ITERATIONS:-10}"
OUTPUT_FILE="${WORKSPACE_DIR}/BENCHMARK.md"
EXEC_LOG="/tmp/corelink-bazel-bench-exec.json"

# Parse flags.
while [[ $# -gt 0 ]]; do
    case "$1" in
        --iterations) ITERATIONS="$2"; shift 2 ;;
        --output)     OUTPUT_FILE="$2"; shift 2 ;;
        *)            echo "Unknown flag: $1"; exit 1 ;;
    esac
done

if [[ -z "${CORELINK_PAT:-}" ]]; then
    echo "ERROR: CORELINK_PAT is not set." >&2
    exit 1
fi

cd "${WORKSPACE_DIR}"

cold_times=()
warm_times=()
warm_hit_ratios=()

echo "Running ${ITERATIONS} cold + ${ITERATIONS} warm iterations..."
echo ""

for i in $(seq 1 "${ITERATIONS}"); do
    printf "  Iteration %2d/%d: " "${i}" "${ITERATIONS}"

    # Cold build — expunge cache first.
    bazel clean --expunge 2>/dev/null
    cold_start=$(date +%s%3N)
    bazel build //:hello 2>/dev/null
    cold_end=$(date +%s%3N)
    cold_ms=$(( cold_end - cold_start ))
    cold_times+=("${cold_ms}")

    # Warm build — expunge local, use remote cache.
    bazel clean --expunge 2>/dev/null
    warm_start=$(date +%s%3N)
    bazel build //:hello \
        --noremote_upload_local_results \
        --execution_log_json_file="${EXEC_LOG}" 2>/dev/null
    warm_end=$(date +%s%3N)
    warm_ms=$(( warm_end - warm_start ))
    warm_times+=("${warm_ms}")

    # Parse cache hit ratio from execution log.
    hit_ratio=$(python3 - <<'EOF'
import json, sys

hits = total = 0
try:
    with open(sys.argv[1]) as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            try:
                entry = json.loads(line)
            except json.JSONDecodeError:
                continue
            if "remoteCacheHit" in entry:
                total += 1
                if entry["remoteCacheHit"]:
                    hits += 1
except FileNotFoundError:
    pass

if total == 0:
    print("0.0")
else:
    print(f"{hits/total*100:.1f}")
EOF
    "${EXEC_LOG}" 2>/dev/null || echo "0.0")

    warm_hit_ratios+=("${hit_ratio}")
    printf "cold=%dms  warm=%dms  hit=%s%%\n" "${cold_ms}" "${warm_ms}" "${hit_ratio}"
done

# Compute statistics with Python (portable; avoids bc/awk differences).
stats=$(python3 - <<'EOF'
import sys, json, statistics

cold = list(map(int, sys.argv[1].split(",")))
warm = list(map(int, sys.argv[2].split(",")))
hits = list(map(float, sys.argv[3].split(",")))

def p95(data):
    s = sorted(data)
    idx = int(len(s) * 0.95)
    return s[min(idx, len(s)-1)]

result = {
    "cold_median_ms":   statistics.median(cold),
    "cold_p95_ms":      p95(cold),
    "warm_median_ms":   statistics.median(warm),
    "warm_p95_ms":      p95(warm),
    "hit_ratio_median": statistics.median(hits),
    "hit_ratio_min":    min(hits),
    "speedup":          statistics.median(cold) / statistics.median(warm) if statistics.median(warm) > 0 else 0,
}
print(json.dumps(result))
EOF
    "$(IFS=,; echo "${cold_times[*]}")" \
    "$(IFS=,; echo "${warm_times[*]}")" \
    "$(IFS=,; echo "${warm_hit_ratios[*]}")")

cold_median=$(echo "${stats}" | python3 -c "import sys,json; d=json.load(sys.stdin); print(int(d['cold_median_ms']))")
cold_p95=$(echo "${stats}" | python3 -c "import sys,json; d=json.load(sys.stdin); print(int(d['cold_p95_ms']))")
warm_median=$(echo "${stats}" | python3 -c "import sys,json; d=json.load(sys.stdin); print(int(d['warm_median_ms']))")
warm_p95=$(echo "${stats}" | python3 -c "import sys,json; d=json.load(sys.stdin); print(int(d['warm_p95_ms']))")
hit_median=$(echo "${stats}" | python3 -c "import sys,json; d=json.load(sys.stdin); print(d['hit_ratio_median'])")
hit_min=$(echo "${stats}" | python3 -c "import sys,json; d=json.load(sys.stdin); print(d['hit_ratio_min'])")
speedup=$(echo "${stats}" | python3 -c "import sys,json; d=json.load(sys.stdin); print(f\"{d['speedup']:.1f}\")")

RUN_DATE=$(date -u +"%Y-%m-%d %H:%M UTC")

cat > "${OUTPUT_FILE}" <<REPORT
# CoreLink Bazel Starter — Benchmark Report

<!-- AUTO-GENERATED by scripts/benchmark.sh — do not edit manually -->

**Last run:** ${RUN_DATE}
**Iterations:** ${ITERATIONS} cold + ${ITERATIONS} warm
**Target:** \`//:hello\` (cc_binary with 1 transitive cc_library dep)

## Results

| Metric | Value | SLA target |
|---|---|---|
| Cold build — median | ${cold_median} ms | — |
| Cold build — p95 | ${cold_p95} ms | — |
| Warm build (cache hit) — median | ${warm_median} ms | ≤ 30 000 ms |
| Warm build (cache hit) — p95 | ${warm_p95} ms | — |
| Cache hit ratio — median | ${hit_median} % | ≥ 80 % |
| Cache hit ratio — min | ${hit_min} % | ≥ 80 % |
| Speedup (cold / warm) | ${speedup}x | — |

## Pass / Fail

$(python3 - <<'PYEOF'
warm = ${warm_median}
hit  = float("${hit_median}")
sla_warm = 30000
sla_hit  = 80.0

warm_ok = warm <= sla_warm
hit_ok  = hit  >= sla_hit

print(f"- Warm build ≤ 30 s: {'PASS' if warm_ok else 'FAIL'} ({warm} ms)")
print(f"- Cache hit ≥ 80 %:  {'PASS' if hit_ok  else 'FAIL'} ({hit} %)")
PYEOF
)

## Raw data (all iterations)

### Cold build times (ms)

\`\`\`
$(IFS=, ; echo "${cold_times[*]}" | tr ',' '\n')
\`\`\`

### Warm build times (ms)

\`\`\`
$(IFS=, ; echo "${warm_times[*]}" | tr ',' '\n')
\`\`\`

### Cache hit ratios (%)

\`\`\`
$(IFS=, ; echo "${warm_hit_ratios[*]}" | tr ',' '\n')
\`\`\`
REPORT

echo ""
echo "Results written to: ${OUTPUT_FILE}"
echo ""
echo "Summary:"
echo "  Cold median: ${cold_median} ms   p95: ${cold_p95} ms"
echo "  Warm median: ${warm_median} ms   p95: ${warm_p95} ms"
echo "  Hit ratio:   ${hit_median} %   (min: ${hit_min} %)"
echo "  Speedup:     ${speedup}x"
