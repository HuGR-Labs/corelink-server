//! `corelink-supply-verify` CLI binary (WI-S12-001).
//!
//! Provides three subcommands for customer-side SLSA L3 provenance verification:
//!
//! - `verify` — Full attestation verification (Fulcio chain + Rekor inclusion + builder identity).
//! - `lookup` — Standalone Rekor log entry lookup by log index (paranoid mode).
//! - `extract` — Extract and display attestation contents without verifying (debug).
//!
//! ## Exit codes
//!
//! | Code | Meaning |
//! |------|---------|
//! | 0    | Success |
//! | 1    | Verification failed (builder mismatch, Rekor missing, Fulcio invalid, schema invalid) |
//! | 2    | Attestation expired |
//! | 3    | IO / parse error |

#![forbid(unsafe_code)]
// CLI binary is explicitly allowed to print to stdout/stderr — this is its purpose.
#![allow(clippy::print_stdout, clippy::print_stderr)]

use std::path::PathBuf;
use std::process;

use clap::{Parser, Subcommand, ValueEnum};
use corelink_supply_verify::{
    types::{BuilderIdentity, SlsaAttestation},
    verifier::{DefaultSlsaVerifier, SlsaProvenanceVerifier},
};

/// CoreLink SLSA L3 supply chain provenance verifier.
///
/// Verifies SLSA L3 build provenance attestations generated by
/// `slsa-github-generator/generator_generic_slsa3.yml` + Fulcio keyless OIDC +
/// Rekor transparency log. Implements INV-SUPPLY-PROVENANCE-IN-REKOR (fail-CLOSED).
#[derive(Debug, Parser)]
#[command(
    name = "corelink-supply-verify",
    version,
    about = "CoreLink SLSA L3 supply chain provenance verifier",
    long_about = None,
)]
struct Cli {
    #[command(subcommand)]
    command: Commands,
}

#[derive(Debug, Subcommand)]
enum Commands {
    /// Verify a SLSA L3 provenance attestation bundle.
    ///
    /// Performs full verification: DSSE envelope validity, in-toto v1.0 schema,
    /// Fulcio certificate structural check, builder identity matching, and
    /// Rekor inclusion proof validation.
    ///
    /// Exit 0 on success; exit 1 on any security failure; exit 3 on IO/parse error.
    Verify(VerifyArgs),

    /// Look up a Rekor log entry by log index (paranoid mode).
    ///
    /// Standalone Rekor lookup without requiring a full bundle file.
    /// Prints the log entry URL and rekor_log_index.
    Lookup(LookupArgs),

    /// Extract attestation contents for inspection (debug mode).
    ///
    /// Displays the parsed attestation without performing cryptographic verification.
    /// Useful for debugging attestation format issues.
    Extract(ExtractArgs),
}

/// Arguments for the `verify` subcommand.
#[derive(Debug, clap::Args)]
struct VerifyArgs {
    /// Path to the provenance bundle file (provenance.intoto.bundle or .jsonl).
    #[arg(long, value_name = "PATH")]
    bundle: PathBuf,

    /// Release tag being verified (e.g., `v0.1.0`). Used for display only.
    #[arg(long, value_name = "TAG")]
    release: String,

    /// Expected builder pattern. Must match the Fulcio certificate SAN URI.
    ///
    /// Can be an org/repo pattern (e.g., `humangr-labs/corelink-server`) or a full
    /// SAN URI (e.g., `https://github.com/humangr-labs/corelink-server/.github/workflows/release-slsa3.yml@refs/tags/v0.1.0`).
    #[arg(long, value_name = "PATTERN")]
    expected_builder: String,

    /// Output format.
    #[arg(long, value_enum, default_value = "text")]
    format: OutputFormat,

    /// CoreLink tenant plan label for metrics (default: `external`).
    #[arg(long, default_value = "external")]
    plan: String,
}

/// Arguments for the `lookup` subcommand.
#[derive(Debug, clap::Args)]
struct LookupArgs {
    /// Rekor log index to look up.
    #[arg(long, value_name = "N")]
    rekor_log_index: u64,

    /// Rekor server URL (default: sigstore public instance).
    #[arg(long, default_value = "https://rekor.sigstore.dev")]
    rekor_server: String,
}

/// Arguments for the `extract` subcommand.
#[derive(Debug, clap::Args)]
struct ExtractArgs {
    /// Path to the provenance bundle file.
    #[arg(long, value_name = "PATH")]
    bundle: PathBuf,

    /// Output format.
    #[arg(long, value_enum, default_value = "json")]
    output_format: OutputFormat,
}

/// Output format for CLI commands.
#[derive(Debug, Clone, ValueEnum)]
enum OutputFormat {
    /// Human-readable text output.
    Text,
    /// Machine-readable JSON output.
    Json,
    /// YAML output.
    Yaml,
}

#[tokio::main]
async fn main() {
    let cli = Cli::parse();

    let exit_code = match cli.command {
        Commands::Verify(args) => run_verify(args).await,
        Commands::Lookup(args) => run_lookup(args),
        Commands::Extract(args) => run_extract(args),
    };

    process::exit(exit_code);
}

/// Run the `verify` subcommand. Returns the process exit code.
async fn run_verify(args: VerifyArgs) -> i32 {
    let bundle_contents = match std::fs::read_to_string(&args.bundle) {
        Ok(c) => c,
        Err(e) => {
            eprintln!("error: failed to read bundle file `{}`: {}", args.bundle.display(), e);
            return 3;
        }
    };

    let attestation: SlsaAttestation = match serde_json::from_str(&bundle_contents) {
        Ok(a) => a,
        Err(e) => {
            eprintln!("error: failed to parse attestation bundle: {}", e);
            return 3;
        }
    };

    // Determine builder identity: try as exact SAN URI first, then org pattern.
    let expected_builder = if args.expected_builder.starts_with("https://") {
        BuilderIdentity::from_exact(&args.expected_builder)
    } else {
        BuilderIdentity::from_org_pattern(&args.expected_builder)
    };

    let verifier = DefaultSlsaVerifier::with_plan(&args.plan);

    match verifier.verify(&attestation, &expected_builder).await {
        Ok(prov) => {
            match args.format {
                OutputFormat::Json => {
                    // Machine-readable JSON output for scripting
                    println!(
                        "{}",
                        serde_json::json!({
                            "status": "ok",
                            "release": args.release,
                            "builder_id": prov.builder_id,
                            "commit_sha": prov.commit_sha,
                            "workflow_ref": prov.workflow_ref,
                            "rekor_log_index": prov.rekor_log_index,
                            "rekor_inclusion_proof_url": prov.rekor_inclusion_proof_url,
                            "fulcio_cert_chain_valid": prov.fulcio_cert_chain_valid,
                            "in_toto_schema_version": prov.in_toto_schema_version,
                            "artifact_digest": prov.artifact_digest,
                        })
                    );
                }
                OutputFormat::Text | OutputFormat::Yaml => {
                    println!("SLSA L3 provenance verification PASSED for release {}", args.release);
                    println!("  builder_id:               {}", prov.builder_id);
                    println!("  commit_sha:               {}", prov.commit_sha);
                    println!("  workflow_ref:             {}", prov.workflow_ref);
                    println!("  rekor_log_index:          {}", prov.rekor_log_index);
                    println!("  rekor_inclusion_proof:    {}", prov.rekor_inclusion_proof_url);
                    println!("  fulcio_cert_chain_valid:  {}", prov.fulcio_cert_chain_valid);
                    println!("  in_toto_schema_version:   {}", prov.in_toto_schema_version);
                    println!("  artifact_digest:          {}", prov.artifact_digest);
                }
            }
            0
        }
        Err(e) => {
            let exit_code = e.exit_code();
            eprintln!("error: SLSA L3 verification FAILED: {}", e);
            if e.is_security_failure() {
                eprintln!(
                    "note: This is a security-critical failure. \
                    Do NOT use this release artifact. \
                    See https://github.com/humangr-labs/corelink-server/security for reporting."
                );
            }
            exit_code
        }
    }
}

/// Run the `lookup` subcommand. Returns the process exit code.
fn run_lookup(args: LookupArgs) -> i32 {
    let url = format!(
        "{}/api/v1/log/entries?logIndex={}",
        args.rekor_server, args.rekor_log_index
    );
    println!("Rekor log entry lookup:");
    println!("  log_index: {}", args.rekor_log_index);
    println!("  server:    {}", args.rekor_server);
    println!("  url:       {}", url);
    println!();
    println!("To verify via rekor-cli:");
    println!(
        "  rekor-cli get --rekor_server {} --log-index {}",
        args.rekor_server, args.rekor_log_index
    );
    0
}

/// Run the `extract` subcommand. Returns the process exit code.
fn run_extract(args: ExtractArgs) -> i32 {
    let bundle_contents = match std::fs::read_to_string(&args.bundle) {
        Ok(c) => c,
        Err(e) => {
            eprintln!("error: failed to read bundle file `{}`: {}", args.bundle.display(), e);
            return 3;
        }
    };

    let attestation: SlsaAttestation = match serde_json::from_str::<SlsaAttestation>(&bundle_contents) {
        Ok(a) => a,
        Err(e) => {
            eprintln!("error: failed to parse attestation bundle: {}", e);
            return 3;
        }
    };

    match args.output_format {
        OutputFormat::Json => {
            // Re-serialize the parsed struct for canonical display
            match serde_json::to_string_pretty(&attestation) {
                Ok(s) => println!("{}", s),
                Err(e) => {
                    eprintln!("error: failed to serialize attestation: {}", e);
                    return 3;
                }
            }
        }
        OutputFormat::Text | OutputFormat::Yaml => {
            println!("Attestation bundle extracted from: {}", args.bundle.display());
            println!("  payloadType:   {}", attestation.payload_type);
            println!("  payload:       {} (base64-encoded, {} chars)", &attestation.payload[..attestation.payload.len().min(32)], attestation.payload.len());
            println!("  signatures:    {} signature(s)", attestation.signatures.len());
            for (i, sig) in attestation.signatures.iter().enumerate() {
                println!("    [{}] key_id: {}", i, if sig.key_id.is_empty() { "(empty)" } else { &sig.key_id });
                println!("    [{}] cert:   {} chars PEM", i, sig.cert.len());
                println!("    [{}] sig:    {} chars", i, sig.sig.len());
                if let Some(ref bundle) = sig.bundle {
                    println!("    [{}] rekor_log_index: {}", i, bundle.rekor_log_index);
                    println!("    [{}] inclusion_proof: {}", i, if bundle.inclusion_proof.is_some() { "present" } else { "MISSING" });
                } else {
                    println!("    [{}] rekor bundle: MISSING (INV-SUPPLY-PROVENANCE-IN-REKOR violation)", i);
                }
            }
        }
    }

    0
}
